-- =====================================================================
-- >>> ABWEICHUNG 20: ON UPDATE CURRENT_TIMESTAMP <<<
-- MySQL aktualisiert diese Spalten automatisch bei jedem UPDATE.
-- Postgres hat kein Äquivalent; nachgebildet über BEFORE-UPDATE-Trigger.
-- Betroffen laut full.sql:
--   test_reviews.reviewtime, unit_reviews.reviewtime,
--   login_session_groups.last_modified (implizit, s. Abweichung 6),
--   admin_sessions.valid_until (bewusst NICHT nachgebildet, s. Abweichung 12)
-- =====================================================================
CREATE OR REPLACE FUNCTION set_reviewtime_on_update() RETURNS trigger AS $$
BEGIN
  NEW.reviewtime := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER test_reviews_reviewtime_bu
  BEFORE UPDATE ON test_reviews
  FOR EACH ROW EXECUTE FUNCTION set_reviewtime_on_update();

CREATE TRIGGER unit_reviews_reviewtime_bu
  BEFORE UPDATE ON unit_reviews
  FOR EACH ROW EXECUTE FUNCTION set_reviewtime_on_update();

CREATE OR REPLACE FUNCTION set_last_modified_on_update() RETURNS trigger AS $$
BEGIN
  NEW.last_modified := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER login_session_groups_last_modified_bu
  BEFORE UPDATE ON login_session_groups
  FOR EACH ROW EXECUTE FUNCTION set_last_modified_on_update();


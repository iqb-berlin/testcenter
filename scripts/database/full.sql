-- >>> ABWEICHUNG 15: mediumblob + UNIQUE mit nullable Spalte <<<
-- (a) mediumblob -> bytea wäre der Typ-Match, aber die einzige Nutzung im
--     Code ist InitDAO: "insert into meta (metaKey, value) values
--     ('dbSchemaVersion', :new_version)" — also ein String. bytea würde
--     PDO-seitig als Stream zurückkommen und den Versionsvergleich brechen.
--     Empfehlung: text. Umgesetzt.
-- (b) `category` ist nullable und Teil des UNIQUE. In MySQL wie in Postgres
--     verhindert das UNIQUE damit KEINE doppelten ('dbSchemaVersion', NULL)-
--     Zeilen. InitDAO verlässt sich auf Einmaligkeit dieser Zeile.
--     Empfehlung: category NOT NULL DEFAULT '' setzen und daraus einen
--     echten PK machen. Da das eine Verhaltensänderung ist, hier NICHT
--     stillschweigend umgesetzt — der MySQL-Zustand ist 1:1 abgebildet.
--     Der korrigierte Zustand steht auskommentiert darunter.
CREATE TABLE meta (
  "metaKey" varchar(100) NOT NULL,       -- Quoting nötig: CamelCase, s. Abweichung 16
  value     text,                        -- war mediumblob, s. Abweichung 15a
  category  varchar(30) DEFAULT NULL,
  CONSTRAINT meta_pk UNIQUE ("metaKey", category)
);
-- weggelassen: UNIQUE KEY `meta_metaKey_category_uindex` -- identisch mit meta_pk
--
-- Empfohlene Variante (bewusst nicht aktiv), s. Abweichung 15b:

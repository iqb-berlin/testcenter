-- =====================================================================
-- unit_defs_attachments
-- =====================================================================
-- >>> ABWEICHUNG 17: STORED GENERATED COLUMN als FK-Bestandteil <<<
-- MySQL:
--   `file_type` enum(...) GENERATED ALWAYS AS (_utf8mb4'Booklet') STORED
--   + FK (workspace_id, booklet_name, file_type) -> files(workspace_id, id, type)
-- Die Spalte ist eine Konstante, die nur existiert, um den FK auf
-- files.type = 'Booklet' einzuschränken.
--
-- Postgres erlaubt in GENERATED ALWAYS AS (...) STORED nur IMMUTABLE
-- Ausdrücke über Spalten derselben Zeile; ein reiner Konstantenausdruck
-- ist zulässig, aber Postgres verbietet Generated Columns als Ziel/Quelle
-- eines FOREIGN KEY *nicht* — der FK funktioniert.
-- Sauberer und ohne Sonderfall ist jedoch eine normale Spalte mit
-- DEFAULT + CHECK. Das ist hier umgesetzt: identische Garantie,
-- keine Generated-Column-Semantik nötig, und WorkspaceDAO:257 schreibt
-- die Spalte ohnehin nie.
-- Empfehlung: so belassen. Wer die Generated Column zwingend spiegeln
-- will, nutzt die auskommentierte Variante darunter.
CREATE TABLE unit_defs_attachments (
  workspace_id    bigint NOT NULL,
  unit_name       varchar(120) COLLATE german2_ci NOT NULL,
  booklet_name    varchar(120) COLLATE german2_ci NOT NULL,
  attachment_type attachment_type NOT NULL,
  variable_id     varchar(100) COLLATE german2_ci NOT NULL,
  file_type       file_type NOT NULL DEFAULT 'Booklet',
  CONSTRAINT unit_defs_attachments_file_type_const CHECK (file_type = 'Booklet'),
  PRIMARY KEY (booklet_name, unit_name, variable_id, workspace_id),
  CONSTRAINT files_fk
    FOREIGN KEY (workspace_id, booklet_name, file_type)
    REFERENCES files (workspace_id, id, type) ON DELETE CASCADE
);
-- Alternative, näher am MySQL-Original:
--   file_type file_type GENERATED ALWAYS AS ('Booklet'::file_type) STORED

CREATE INDEX files_fk_idx ON unit_defs_attachments (workspace_id, booklet_name, file_type);


-- =====================================================================
-- file_relations
-- =====================================================================
-- >>> ABWEICHUNG 18: UNIQUE über nullable `object_name` <<<
-- `object_name` ist nullable und Teil des UNIQUE. Verhalten in MySQL und
-- Postgres identisch (NULL != NULL), daher 1:1 übernommen.
-- Achtung: WorkspaceDAO:555 nutzt "replace into" — das muss unter Postgres

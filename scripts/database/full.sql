-- IQB-Testcenter DB -- PostgreSQL
--
-- Übersetzung von scripts/database/full.sql (MySQL 8 / InnoDB) nach PostgreSQL.
-- Zielzustand: initiale Befüllung einer *leeren* Postgres-Datenbank.
--
-- Reihenfolge der Statements = Abhängigkeitsreihenfolge der Fremdschlüssel.
-- Alle Stellen ohne 1:1-Übersetzung sind mit  >>> ABWEICHUNG <<<  markiert
-- und am Dateiende unter "MIGRATIONSHINWEISE" zusammengefasst.

BEGIN;

-- =====================================================================
-- >>> ABWEICHUNG 1: CHARACTER SET / COLLATION <<<
-- MySQL: utf8mb3 / utf8mb3_german2_ci bzw. utf8mb4 / utf8mb4_0900_ai_ci
--        (ci = case-insensitive, accent-insensitive) sowie utf8mb3_bin.
-- Postgres kennt keine Per-Spalten-Charsets; die Datenbank ist UTF8.
-- Case-Insensitivity wird über eine nicht-deterministische ICU-Collation
-- nachgebildet. Diese ersetzt utf8mb3_german2_ci.
-- Empfehlung: Datenbank mit  ENCODING 'UTF8'  anlegen und diese Collation
-- an allen Textspalten verwenden, die in MySQL *_ci waren.
-- Benötigt Postgres >= 12 mit ICU-Support (ab PG 16 auch als DB-Default nutzbar).
-- =====================================================================
CREATE COLLATION IF NOT EXISTS german2_ci (
  provider      = icu,
  locale        = 'de-DE-u-ks-level2',  -- level2 = case-insensitive, akzentsensitiv
  deterministic = false
);

-- >>> ABWEICHUNG 2: ENUM-Typen <<<
-- MySQL deklariert enum(...) inline an der Spalte. Postgres benötigt
-- benannte Typen. Die Wertelisten sind 1:1 übernommen.
CREATE TYPE file_type AS ENUM (
  'Testtakers', 'SysCheck', 'Booklet', 'Unit', 'Resource'
);

CREATE TYPE verona_module_type AS ENUM (
  'player', 'schemer', 'editor', ''
);

CREATE TYPE file_relationship_type AS ENUM (
  'hasBooklet', 'containsUnit', 'usesPlayer', 'usesPlayerResource',
  'isDefinedBy', 'usesScheme', 'unknown'
);

CREATE TYPE attachment_type AS ENUM ('capture-image');

CREATE TYPE assignment_scope AS ENUM ('global', 'group', 'user');


-- =====================================================================
-- users
-- =====================================================================
-- >>> ABWEICHUNG 3: bigint unsigned <<<
-- Postgres kennt kein UNSIGNED. Alle `bigint unsigned` werden zu `bigint`.
-- Die Wertebereichshalbierung ist praktisch irrelevant; negative Werte
-- werden über CHECK-Constraints an den ID-Spalten nicht erzwungen, da
-- alle IDs aus Identity-Sequenzen stammen.
--
-- >>> ABWEICHUNG 4: AUTO_INCREMENT <<<
-- MySQL AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY.
-- "BY DEFAULT" (nicht "ALWAYS"), damit explizite ID-Inserts (Tests,
-- Fixtures, Datenmigration) weiterhin möglich sind.
-- Wichtig: PDO::lastInsertId() ohne Argument nutzt unter pgsql lastval()
-- und funktioniert mit IDENTITY korrekt.
--
-- >>> ABWEICHUNG 5: tinyint(1) <<<
-- MySQL nutzt tinyint(1) als Boolean-Ersatz und liefert 0/1.
-- Hier: boolean. Siehe Migrationshinweis Nr. 5 zu den Folgen im PHP-Code.
CREATE TABLE users (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            varchar(50) COLLATE german2_ci NOT NULL,
  password        varchar(100) COLLATE german2_ci NOT NULL,
  email           varchar(100) COLLATE german2_ci DEFAULT NULL,
  is_superadmin   boolean NOT NULL DEFAULT false,
  pw_set_by_admin boolean NOT NULL DEFAULT false
);


-- =====================================================================
-- workspaces
-- =====================================================================
CREATE TABLE workspaces (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           varchar(50) COLLATE german2_ci NOT NULL,
  workspace_hash varchar(255) COLLATE german2_ci NOT NULL DEFAULT '',
  content_type   varchar(255) COLLATE german2_ci NOT NULL DEFAULT 'mixed'
);


-- =====================================================================
-- login_session_groups
-- =====================================================================
-- >>> ABWEICHUNG 6: `last_modified timestamp NOT NULL` <<<
-- In MySQL erhält die *erste* TIMESTAMP-Spalte einer Tabelle implizit
-- DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
-- (sofern explicit_defaults_for_timestamp=OFF). Postgres hat dieses
-- Verhalten nicht. Hier explizit als DEFAULT gesetzt; das ON UPDATE
-- wird über den Trigger am Dateiende nachgebildet.
--
-- >>> ABWEICHUNG 7: timestamp-Typ <<<
-- MySQL TIMESTAMP speichert UTC und konvertiert in die Session-Zeitzone.
-- Das Äquivalent ist `timestamptz`, nicht `timestamp`.
-- Empfehlung: timestamptz verwenden (hier umgesetzt) und die
-- Server-Zeitzone in postgresql.conf / im Connection-String auf UTC setzen.
CREATE TABLE login_session_groups (
  workspace_id  bigint NOT NULL,
  group_label   text COLLATE german2_ci NOT NULL,
  group_name    varchar(100) COLLATE german2_ci NOT NULL,
  token         varchar(50) COLLATE german2_ci NOT NULL,
  last_modified timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (workspace_id, group_name),
  CONSTRAINT login_session_groups_unique_token UNIQUE (token)
);


-- =====================================================================
-- login_sessions
-- =====================================================================
-- >>> ABWEICHUNG 8: utf8mb3_bin auf `name` <<<
-- `login_sessions`.`name` und `logins`.`name` sind in MySQL *_bin,
-- also case-SENSITIV — im Gegensatz zu allen anderen Spalten.
-- Das ist beabsichtigt (Login-Namen müssen exakt matchen).
-- In Postgres entspricht das der Default-Collation "C" bzw. schlicht
-- dem Weglassen der german2_ci-Collation. Hier bewusst OHNE COLLATE.
CREATE TABLE login_sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         varchar(50) NOT NULL,                       -- case-sensitiv, s. Abweichung 8
  workspace_id bigint NOT NULL,
  token        varchar(50) COLLATE german2_ci NOT NULL,
  group_name   varchar(100) COLLATE german2_ci NOT NULL,
  CONSTRAINT unique_login_session UNIQUE (name, workspace_id),
  CONSTRAINT fk_login_workspace
    FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
  CONSTRAINT login_session_groups_fk
    FOREIGN KEY (workspace_id, group_name)
    REFERENCES login_session_groups (workspace_id, group_name)
    ON DELETE CASCADE ON UPDATE CASCADE
);

-- >>> ABWEICHUNG 9: sekundäre Indizes <<<
-- MySQL legt KEY(...) innerhalb von CREATE TABLE an; Postgres braucht
-- separate CREATE INDEX. Redundante Indizes aus full.sql wurden dabei
-- weggelassen, siehe Migrationshinweis Nr. 9.
CREATE INDEX index_fk_login_workspace ON login_sessions (workspace_id);
CREATE INDEX index_fk_logins          ON login_sessions (name);
CREATE INDEX login_sessions_token_index ON login_sessions (token);
CREATE INDEX login_sessions_groups_fk ON login_sessions (workspace_id, group_name);
-- weggelassen: KEY `index_fk_login_session_login` (`id`) -- dupliziert den PK


-- =====================================================================
-- person_sessions
-- =====================================================================
-- >>> ABWEICHUNG 10: UNIQUE (login_sessions_id, name_suffix) mit NULL <<<
-- `name_suffix` ist nullable. MySQL wie Postgres behandeln NULL in
-- UNIQUE-Indizes als "immer verschieden", d.h. beliebig viele Zeilen mit
-- name_suffix IS NULL sind in BEIDEN Systemen erlaubt. Verhalten identisch.
-- Nur zur Info: Postgres 15+ könnte über NULLS NOT DISTINCT strenger sein;
-- das wird hier bewusst NICHT gesetzt, um MySQL-Semantik beizubehalten.
CREATE TABLE person_sessions (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              varchar(50) COLLATE german2_ci NOT NULL,
  login_sessions_id bigint NOT NULL,
  valid_until       timestamptz DEFAULT NULL,
  token             varchar(50) COLLATE german2_ci DEFAULT NULL,
  name_suffix       varchar(100) COLLATE german2_ci DEFAULT NULL,
  CONSTRAINT unique_person_session UNIQUE (login_sessions_id, name_suffix),
  CONSTRAINT fk_person_login
    FOREIGN KEY (login_sessions_id) REFERENCES login_sessions (id) ON DELETE CASCADE
);

CREATE INDEX index_fk_person_login       ON person_sessions (login_sessions_id);
CREATE INDEX person_sessions_token_index ON person_sessions (token);
-- weggelassen: UNIQUE KEY `person_sessions_id_uindex` (`id`) -- dupliziert den PK



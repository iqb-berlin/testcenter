-- =====================================================================
-- Triggers
-- =====================================================================
-- Both reviewtime columns had ON UPDATE CURRENT_TIMESTAMP in MySQL, which has no PostgreSQL
-- equivalent. No other column needs one: login_session_groups.last_modified only looked like it
-- did, because MySQL grants the first TIMESTAMP column of a table an implicit ON UPDATE — but only
-- while explicit_defaults_for_timestamp is off, and MySQL 8 defaults it on. AdminDAO writes that
-- column explicitly, so a trigger would silently discard the value it passes.
CREATE OR REPLACE FUNCTION set_reviewtime_on_update() RETURNS trigger AS $$
BEGIN
  NEW.reviewtime := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER test_reviews_reviewtime_bu
  BEFORE UPDATE ON test_reviews
  FOR EACH ROW EXECUTE FUNCTION set_reviewtime_on_update();

CREATE TRIGGER unit_reviews_reviewtime_bu
  BEFORE UPDATE ON unit_reviews
  FOR EACH ROW EXECUTE FUNCTION set_reviewtime_on_update();



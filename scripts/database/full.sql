-- =====================================================================
-- file_relations
-- =====================================================================
-- WorkspaceDAO::storeRelations() inserts against unique_combination with ON CONFLICT DO NOTHING,
-- because a file may declare the same relation twice. That deduplication silently stops working
-- for any row that leaves `object_name` NULL: NULL never collides, so the constraint does not
-- catch it. The current writer always supplies a name.
CREATE TABLE file_relations (
  workspace_id      bigint NOT NULL,
  subject_name      varchar(120) NOT NULL,
  subject_type      file_type NOT NULL,
  relationship_type file_relationship_type NOT NULL,
  object_type       file_type NOT NULL,
  object_name       varchar(120) DEFAULT NULL,
  CONSTRAINT unique_combination UNIQUE (
    workspace_id, subject_name, subject_type, relationship_type, object_type, object_name
  ),
  CONSTRAINT file_relations_files_fk
    FOREIGN KEY (workspace_id, subject_name, subject_type)
    REFERENCES files (workspace_id, name, type) ON DELETE CASCADE
);



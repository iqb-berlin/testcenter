-- IQB Testcenter — complete PostgreSQL schema.
--
-- This file is hand-maintained, not dumped from a running database.
-- `backend/initialize.php` runs it once against an empty database and then applies every patch in
-- `scripts/database/patches.d` that the version stamped at the end of this file does not already
-- cover. `TestEnvironment::createTestDatabase()` runs it alone to build the test database.
-- Adding a patch therefore means applying the same change here — see docs/agent/database.md.
--
-- Statement order is foreign-key dependency order.

BEGIN;

-- Case-insensitive equality for human-readable text, as the MySQL releases had on most columns.
-- Being non-deterministic, this collation makes PostgreSQL reject LIKE, ILIKE and regular
-- expressions on any column using it ("nondeterministic collations are not supported for LIKE").
-- No query needs that today; where one does, compare with COLLATE "C" in the query itself or make
-- that column deterministic and index lower(...).
CREATE COLLATION IF NOT EXISTS german2_ci (
  provider      = icu,
  locale        = 'de-DE-u-ks-level2',  -- level2: case-insensitive, accent-sensitive
  deterministic = false
);

-- Columns deliberately declared WITHOUT german2_ci fall into two groups:
--
--   1. Identifiers that must match exactly: login_sessions.name, logins.name, logins.source,
--      files.name, file_relations.subject_name and object_name. These were utf8mb3_bin or
--      varbinary in MySQL for that reason. varbinary never carried binary data — it was only a way
--      to force a case-sensitive comparison — so varchar is the faithful translation, not bytea.
--
--   2. Machine-generated or machine-matched values: meta.metaKey and category, test_commands
--      keyword and parameter, everything in unit_data, and the assets and asset_assignment text
--      columns. These compared case-insensitively under MySQL, but only by accident: the patches
--      creating them omitted COLLATE and inherited the mysql:8.4 server default
--      utf8mb4_0900_ai_ci, while every patch that stated a collation chose german2_ci. Their values
--      are generated ids, client-supplied part ids, XML slot names and code literals, and PHP
--      already compares them case-sensitively (see WorkspaceCache::hasAsset()). Case-sensitive is
--      the intended state here; do not "restore" the inherited collation.

CREATE TYPE file_type AS ENUM (
  'Testtakers', 'SysCheck', 'Booklet', 'Unit', 'Resource'
);

CREATE TYPE verona_module_type AS ENUM (
  'player', 'schemer', 'editor', ''
);

CREATE TYPE file_relationship_type AS ENUM (
  'hasBooklet', 'containsUnit', 'usesPlayer', 'usesPlayerResource',
  'isDefinedBy', 'usesScheme', 'unknown'
);

CREATE TYPE attachment_type AS ENUM ('capture-image');

CREATE TYPE assignment_scope AS ENUM ('global', 'group', 'user');

-- InitDAO::clearDB() drops these types by name after dropping the tables, because PostgreSQL keeps
-- them once their consuming tables are gone. Adding a type here means adding it to
-- InitDAO::schemaTypes as well, or --overwrite_existing_installation breaks on the next run.


-- Identity columns are GENERATED BY DEFAULT, not ALWAYS, so that tests, fixtures and restores can
-- insert explicit ids. Doing so does not advance the sequence — backend/test/unit/testdata.sql and
-- InitDAO::createWorkspaceIfMissing() resynchronize it with setval() afterwards.



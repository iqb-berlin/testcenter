-- =====================================================================
-- MIGRATIONSHINWEISE — kein 1:1-Mapping, Handlungsbedarf im Code
-- =====================================================================
--
--  1. COLLATION (Abweichung 1)
--     Das MySQL-Schema mischt drei Collations: utf8mb3_german2_ci (Default),
--     utf8mb3_bin (Login-Namen, case-sensitiv) und utf8mb4_0900_ai_ci
--     (test_commands, meta, unit_data, assets, asset_assignment).
--     Abgebildet auf: german2_ci (ICU, nicht-deterministisch) bzw.
--     Default-Collation (case-sensitiv).
--     ACHTUNG: Nicht-deterministische Collations verbieten in Postgres
--     die Pattern-Operatoren LIKE/ILIKE und reguläre Ausdrücke auf der
--     betroffenen Spalte (Fehler: "nondeterministic collations are not
--     supported for LIKE"). Vor dem Rollout prüfen:
--         grep -rn "like" --include="*.php" backend/src/dao
--     Wo LIKE nötig ist, entweder
--       (a) im Query explizit umkollationieren:
--           WHERE name COLLATE "C" LIKE :pattern
--       (b) oder die Spalte deterministisch lassen und die
--           Case-Insensitivität über lower(...) + Functional Index lösen.
--     Empfehlung: (b) für Spalten, die tatsächlich mit LIKE durchsucht
--     werden; german2_ci nur dort, wo reine Gleichheitsvergleiche laufen.
--
--  2. ENUM (Abweichung 2)
--     Als eigene Typen umgesetzt. Neue Werte brauchen künftig
--     ALTER TYPE ... ADD VALUE statt ALTER TABLE ... MODIFY.
--     Alternative wäre varchar + CHECK; das ist migrationsfreundlicher,
--     weicht aber stärker vom Original ab.
--     Empfehlung: bei Typen, die absehbar wachsen (file_relationship_type),
--     varchar + CHECK erwägen.
--
--  4. AUTO_INCREMENT-Startwerte
--     full.sql enthält AUTO_INCREMENT=2 (users, workspaces), =16
--     (login_sessions, person_sessions), =33 (tests). Das sind Artefakte
--     des Dumps aus einer Testdatenbank, KEIN Zielzustand. Für eine leere
--     DB starten alle Identity-Sequenzen bei 1 — hier bewusst so.
--     Werden Daten aus MySQL übernommen, danach unbedingt:
--         SELECT setval(pg_get_serial_sequence('users','id'),
--                       COALESCE((SELECT max(id) FROM users), 0) + 1, false);
--     analog für workspaces, login_sessions, person_sessions, tests,
--     test_reviews, unit_reviews, assets, asset_assignment.
--
--  5. tinyint(1) -> boolean (Abweichung 5)
--     MySQL liefert 0/1 als String; Postgres liefert true/false (PDO: bool
--     bzw. 't'/'f' je nach Treiberversion). Strikte Vergleiche wie
--     `if ($row['locked'] === '1')` brechen.
--     Alternative ohne Codeanpassung: smallint statt boolean.
--     Empfehlung: boolean beibehalten und die Vergleichsstellen prüfen —
--     das ist der sauberere Zielzustand. Betroffen: users.is_superadmin,
--     users.pw_set_by_admin, tests.locked, tests.running,
--     test_commands.executed, files.is_valid.
--     NICHT umgestellt: test_reviews.priority und unit_reviews.priority —
--     die sind zwar als tinyint(1) deklariert, tragen aber echte
--     Prioritätsstufen (0-3), daher smallint.
--
--  9. Redundante Indizes
--     full.sql enthält mehrere Indizes, die den PK oder einen anderen
--     UNIQUE-Index duplizieren. Diese sind hier weggelassen (jeweils am
--     Ort kommentiert): person_sessions_id_uindex, units.test_id,
--     test_commands_id_uindex, index_fk_login_session_login,
--     file_relations_subject_index, meta_metaKey_category_uindex,
--     index_fk_workspace_users_workspace.
--     Das ist eine bewusste Bereinigung, keine Übersetzungslücke.
--
-- 16. Bezeichner-Case (meta."metaKey")
--     Postgres faltet unquotierte Bezeichner nach lowercase. `metaKey`
--     bleibt deshalb nur mit doppelten Anführungszeichen erhalten.
--     InitDAO.class.php:392/397 schreibt `metaKey` unquotiert —
--     das läuft unter Postgres in einen "column metakey does not exist".
--     Empfehlung: Spalte in `meta_key` umbenennen und den Code anpassen,
--     statt dauerhaft mit Quoting zu leben. Hier bewusst 1:1 belassen,
--     damit dieses Skript den Ist-Zustand abbildet.
--     Gleiches gilt für die Spaltennamen `timestamp` (test_commands,
--     test_logs, unit_logs) — reserviertes Wort, hier gequotet.
--
-- 18. REPLACE INTO
--     Kein Postgres-Äquivalent. Betroffen:
--       WorkspaceDAO:160 (files), :257 (unit_defs_attachments),
--       :555 (file_relations)
--     Zu ersetzen durch INSERT ... ON CONFLICT (...) DO UPDATE SET ...
--     Semantischer Unterschied: REPLACE löscht die alte Zeile und fügt neu
--     ein (löst damit ON DELETE CASCADE der referenzierenden Tabellen aus!),
--     ON CONFLICT DO UPDATE aktualisiert nur. Für `files` ist das relevant:
--     unter MySQL räumt ein REPLACE die abhängigen file_relations und
--     unit_defs_attachments mit ab, unter Postgres nicht.
--     Empfehlung: an diesen Stellen bewusst entscheiden — für `files`
--     vermutlich explizites DELETE + INSERT in einer Transaktion, um das
--     bisherige Verhalten zu erhalten.
--     Zusatz für file_relations: ON CONFLICT greift nicht, wenn
--     object_name NULL ist (NULL kollidiert nie). Dort entweder
--     NULLS NOT DISTINCT (PG 15+) am UNIQUE ergänzen oder object_name
--     auf NOT NULL DEFAULT '' umstellen.
--
-- 21. TRUNCATE-Statements
--     Die `TRUNCATE <table>;` nach jedem CREATE in full.sql dienen dort
--     dem Zurücksetzen des AUTO_INCREMENT nach einem Dump. Für eine leere
--     Postgres-DB sind sie gegenstandslos und wurden weggelassen.
--     (Postgres bräuchte ohnehin TRUNCATE ... RESTART IDENTITY CASCADE.)
--
-- 22. ENGINE=InnoDB / DEFAULT CHARSET
--     Ohne Entsprechung und ersatzlos entfallen — Postgres hat nur eine
--     Storage-Engine, und Transaktionalität/Referenzielle Integrität sind
--     dort Default.

const fs = require('fs');
const path = require('path');

/** Generate normalized calculator types and defaults from the booklet definition. */
module.exports = (done) => {
  const root = path.resolve(__dirname, '..');
  const booklet = JSON.parse(fs.readFileSync(`${root}/definitions/booklet/booklet.json`).toString());
  const definition = booklet.$defs.Calculator;
  const properties = Object.entries(definition.properties);
  const fieldName = name => name[0].toLowerCase() + name.slice(1);
  const literal = value => JSON.stringify(value).replaceAll('"', '\'');
  const list = values => `[${values.map(literal).join(', ')}]`;
  const enumName = name => `calculator${name[0].toUpperCase() + name.slice(1)}Values`;
  const output = ['// this file is automatically generated. do not change anything here directly!'];
  for (const [name, property] of properties) {
    if (property.enum) output.push(`export const ${enumName(name)} = ${list(property.enum)} as const;`);
  }
  const attributes = properties.map(([name]) => name).filter(name => name !== 'Journal');
  output.push(`export const calculatorAttributeNames = ${list(attributes)} as const;`, '');
  output.push('export const calculatorDefaults = {');
  output.push(properties.filter(([, property]) => 'default' in property)
    .map(([name, property]) => `  ${fieldName(name)}: ${literal(property.default)}`).join(',\n'));
  output.push('} as const;', '', 'export const calculatorMinimums = {');
  output.push(properties.filter(([, property]) => 'minimum' in property)
    .map(([name, property]) => `  ${fieldName(name)}: ${property.minimum}`).join(',\n'));
  output.push('} as const;', '', 'export interface CalculatorConfiguration {');
  for (const [name, property] of properties) {
    const type = property.enum ?
      `typeof ${enumName(name)}[number]` :
      { integer: 'number', string: 'string' }[property.type];
    if (!type) throw new Error(`Unsupported calculator property: ${name}`);
    output.push(`  readonly ${fieldName(name)}: ${type};`);
  }
  output.push('}', '');
  fs.writeFileSync(`${root}/common/src/interfaces/calculator.interfaces.ts`, output.join('\n'));
  done();
};
